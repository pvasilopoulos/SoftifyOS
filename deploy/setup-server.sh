#!/usr/bin/env bash
# =============================================================================
# SoftifyOS – one-time server setup (Ubuntu 22.04 / 24.04 with Plesk)
#
#   sudo bash /opt/softifyos/deploy/setup-server.sh
#
# Installs Node.js (latest LTS line), PostgreSQL 17, PM2, creates the "softify" system user,
# the database and a production .env with freshly generated secrets.
# Safe to run again: existing database, password and .env are kept.
# Everything can be overridden with environment variables, e.g.  WEB_PORT=3100 sudo -E bash ...
# =============================================================================
set -euo pipefail

DOMAIN="${DOMAIN:-app.softify.gr}"
APP_USER="${APP_USER:-softify}"
APP_DIR="${APP_DIR:-/opt/softifyos}"
DB_NAME="${DB_NAME:-softifyos}"
DB_USER="${DB_USER:-softify}"
WEB_PORT="${WEB_PORT:-3000}"
API_PORT="${API_PORT:-4000}"
NODE_MAJOR="${NODE_MAJOR:-26}"          # Node.js 26 = current LTS (Nov 2026)
PG_MAJOR="${PG_MAJOR:-17}"
MAIL_FROM="${MAIL_FROM:-SoftifyOS <no-reply@softify.gr>}"
ADMIN_MAIL="${ADMIN_MAIL:-admin@softify.gr}"

c() { echo -e "\n\033[1;35m==> $*\033[0m"; }
die() { echo -e "\n\033[1;31m✗ $*\033[0m" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Τρέξε το script ως root: sudo bash $0"
[ -f "$APP_DIR/package.json" ] || die "Δεν βρέθηκε ο κώδικας στο $APP_DIR. Αποσυμπίεσε πρώτα το πακέτο έκδοσης εκεί."
. /etc/os-release
[ "${ID:-}" = "ubuntu" ] || echo "Προσοχή: δοκιμασμένο σε Ubuntu (βρέθηκε: ${PRETTY_NAME:-άγνωστο})."

ENV_FILE="$APP_DIR/.env"

# --- Ports (only on first install; later they are ours) ---------------------------
if [ ! -f "$ENV_FILE" ]; then
  for p in "$WEB_PORT" "$API_PORT"; do
    if ss -ltnH "sport = :$p" | grep -q .; then
      die "Η θύρα $p χρησιμοποιείται ήδη. Διάλεξε άλλη, π.χ.: WEB_PORT=3100 API_PORT=4100 sudo -E bash $0"
    fi
  done
fi

c "Βασικά πακέτα"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq || echo "Προσοχή: κάποιο αποθετήριο apt απέτυχε (συνεχίζουμε). Δες: apt-get update"
apt-get install -y -qq ca-certificates curl gnupg openssl build-essential >/dev/null

# --- Node.js ----------------------------------------------------------------------
CUR_NODE="$(command -v node >/dev/null && node -p 'process.versions.node.split(".")[0]' || echo 0)"
if [ "$CUR_NODE" -lt "$NODE_MAJOR" ]; then
  c "Εγκατάσταση Node.js $NODE_MAJOR (LTS)"
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash - >/dev/null
  apt-get install -y -qq nodejs >/dev/null
fi
echo "Node $(node -v), npm $(npm -v)"

c "PM2 (process manager)"
npm install -g pm2@latest --no-fund --no-audit >/dev/null
echo "PM2 $(pm2 -v)"

# --- PostgreSQL -------------------------------------------------------------------
if ! dpkg -s "postgresql-$PG_MAJOR" >/dev/null 2>&1; then
  c "Εγκατάσταση PostgreSQL $PG_MAJOR"
  apt-get install -y -qq postgresql-common >/dev/null
  if ! /usr/share/postgresql-common/pgdg/apt.postgresql.org.sh -y >/dev/null; then
    # Ubuntu releases past end of life (e.g. 20.04 focal) live on apt-archive.postgresql.org
    echo "Το apt.postgresql.org δεν έχει πια αυτή την έκδοση Ubuntu: χρήση apt-archive.postgresql.org"
    for f in /etc/apt/sources.list.d/pgdg*; do [ -f "$f" ] && sed -i 's#://apt\.postgresql\.org/#://apt-archive.postgresql.org/#' "$f"; done
    apt-get update -qq || true
  fi
  apt-get install -y -qq "postgresql-$PG_MAJOR" >/dev/null
fi
# If Plesk already runs another PostgreSQL, Ubuntu gives this cluster the next free port
if ! pg_lsclusters -h | awk -v v="$PG_MAJOR" '$1==v {f=1} END {exit !f}'; then
  # Some servers (e.g. with Plesk) set create_main_cluster = false: create it ourselves
  c "Δημιουργία cluster PostgreSQL $PG_MAJOR"
  pg_createcluster "$PG_MAJOR" main --start >/dev/null
fi
PG_PORT="$(pg_lsclusters -h | awk -v v="$PG_MAJOR" '$1==v {print $3; exit}')"
[ -n "$PG_PORT" ] || die "Δεν βρέθηκε cluster PostgreSQL $PG_MAJOR (pg_lsclusters)."
systemctl enable --now "postgresql@${PG_MAJOR}-main" >/dev/null
echo "PostgreSQL $PG_MAJOR στη θύρα $PG_PORT"

# Memory-based tuning (written once; edit the file to adjust)
TUNE="/etc/postgresql/$PG_MAJOR/main/conf.d/softifyos.conf"
if [ ! -f "$TUNE" ]; then
  c "Ρύθμιση PostgreSQL για μεγάλο όγκο δεδομένων"
  MEM_MB=$(( $(awk '/MemTotal/ {print $2}' /proc/meminfo) / 1024 ))
  mkdir -p "$(dirname "$TUNE")"
  cat >"$TUNE" <<EOF
# SoftifyOS tuning for ${MEM_MB} MB RAM (generated by setup-server.sh)
shared_buffers = $(( MEM_MB / 4 ))MB
effective_cache_size = $(( MEM_MB * 3 / 4 ))MB
maintenance_work_mem = $(( MEM_MB / 16 > 2048 ? 2048 : MEM_MB / 16 ))MB
work_mem = 32MB
max_connections = 200
random_page_cost = 1.1
effective_io_concurrency = 200
wal_compression = on
checkpoint_completion_target = 0.9
EOF
  systemctl restart "postgresql@${PG_MAJOR}-main"
fi

# --- System user --------------------------------------------------------------------
if ! id "$APP_USER" >/dev/null 2>&1; then
  c "Χρήστης συστήματος $APP_USER"
  useradd --system --create-home --home-dir "/home/$APP_USER" --shell /bin/bash "$APP_USER"
fi
chown -R "$APP_USER:$APP_USER" "$APP_DIR"

# --- Database + .env (first run only) ---------------------------------------------
if [ ! -f "$ENV_FILE" ]; then
  c "Βάση δεδομένων και .env"
  DB_PASS="$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 40)"
  sudo -u postgres psql -p "$PG_PORT" -v ON_ERROR_STOP=1 -q <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$DB_USER') THEN
    CREATE ROLE "$DB_USER" LOGIN CREATEROLE PASSWORD '$DB_PASS';
  ELSE
    ALTER ROLE "$DB_USER" LOGIN CREATEROLE PASSWORD '$DB_PASS';
  END IF;
END \$\$;
SQL
  if ! sudo -u postgres psql -p "$PG_PORT" -Atc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1; then
    sudo -u postgres createdb -p "$PG_PORT" -O "$DB_USER" -E UTF8 -T template0 --locale=C.UTF-8 "$DB_NAME"
  fi
  sudo -u postgres psql -p "$PG_PORT" -d "$DB_NAME" -qc "CREATE EXTENSION IF NOT EXISTS pg_trgm"

  JWT_SECRET="$(openssl rand -base64 64 | tr -d '\n=' | tr '+/' '-_')"
  # VAPID keys (P-256) for Web Push. Never change them later: existing device subscriptions depend on them.
  read -r VAPID_PUBLIC VAPID_PRIVATE < <(node -e '
    const c = require("crypto").createECDH("prime256v1"); c.generateKeys();
    const priv = c.getPrivateKey(); const p = Buffer.concat([Buffer.alloc(32 - priv.length), priv]);
    console.log(c.getPublicKey().toString("base64url"), p.toString("base64url"));')

  cat >"$ENV_FILE" <<EOF
# SoftifyOS production settings (generated $(date -u +%F)). Keep this file private.
DATABASE_URL=postgres://$DB_USER:$DB_PASS@127.0.0.1:$PG_PORT/$DB_NAME
DB_POOL_MAX=20
DB_PREPARE=true

API_PORT=$API_PORT
API_HOST=127.0.0.1
WEB_PORT=$WEB_PORT
JWT_SECRET=$JWT_SECRET
COOKIE_SECURE=true

VAPID_PUBLIC_KEY=$VAPID_PUBLIC
VAPID_PRIVATE_KEY=$VAPID_PRIVATE
VAPID_SUBJECT=mailto:$ADMIN_MAIL

API_INTERNAL_URL=http://127.0.0.1:$API_PORT
APP_URL=https://$DOMAIN

# Plesk mail server (Postfix) on the same machine
SMTP_HOST=localhost
SMTP_PORT=25
SMTP_SECURE=false
SMTP_USER=
SMTP_PASS=
SMTP_FROM=$MAIL_FROM
EOF
  chown "$APP_USER:$APP_USER" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "Δημιουργήθηκε το $ENV_FILE (κωδικοί και κλειδιά παράχθηκαν αυτόματα)."
else
  echo "Υπάρχει ήδη $ENV_FILE: δεν αλλάζει."
fi

# --- PM2 as a systemd service (starts after reboot) ---------------------------------
c "Αυτόματη εκκίνηση μετά από επανεκκίνηση"
env PATH="$PATH" pm2 startup systemd -u "$APP_USER" --hp "/home/$APP_USER" >/dev/null
systemctl enable "pm2-$APP_USER" >/dev/null 2>&1 || true

# --- Backups: database + documents every night, restore test every Sunday ----------
c "Backups"
apt-get install -y -qq gnupg rclone >/dev/null 2>&1 || apt-get install -y -qq gnupg >/dev/null
BACKUP_DIR="/var/backups/softifyos"
# Owned by the app user: the worker runs the same script for "Back up now" in Settings → Backups
mkdir -p "$BACKUP_DIR"; chown "$APP_USER":"$APP_USER" "$BACKUP_DIR"; chmod 700 "$BACKUP_DIR"
grep -q '^BACKUP_DIR=' "$ENV_FILE" || echo "BACKUP_DIR=$BACKUP_DIR" >> "$ENV_FILE"
mkdir -p /var/log/softifyos-backup; chown "$APP_USER":"$APP_USER" /var/log/softifyos-backup
cat >/etc/cron.d/softifyos-backup <<EOF
# SoftifyOS: database + documents at 03:15 (14 daily, 8 weekly, 12 monthly), restore test on Sundays at 05:00
15 3 * * * $APP_USER APP_DIR=$APP_DIR bash $APP_DIR/deploy/backup.sh >> /var/log/softifyos-backup/backup.log 2>&1
0 5 * * 0 root APP_DIR=$APP_DIR bash $APP_DIR/deploy/restore.sh --verify >> /var/log/softifyos-backup/verify.log 2>&1
EOF

c "Η αρχική εγκατάσταση ολοκληρώθηκε"
cat <<EOF

Επόμενα βήματα:
  1) sudo bash $APP_DIR/deploy/deploy.sh
  2) Plesk → $DOMAIN → Apache & nginx Settings:
       • ξετσέκαρε "Serve static files directly by nginx"
       • στο "Additional nginx directives" επικόλλησε το $APP_DIR/deploy/nginx-additional-directives.conf
         (θύρες: web $WEB_PORT, api $API_PORT)
  3) Δημιούργησε τον οργανισμό σου:
       sudo -u $APP_USER -H bash -c 'cd $APP_DIR && npm run tenant:create -- --slug softify --name "Softify" --email $ADMIN_MAIL --full-name "Όνομα Επώνυμο"'
EOF
